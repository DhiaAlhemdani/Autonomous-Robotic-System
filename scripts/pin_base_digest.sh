#!/usr/bin/env bash
# Writes .env (git-ignored) from docker/base/pins.env, which is committed.
#
#   ./scripts/pin_base_digest.sh            use the committed pins; fail if the digest is unset
#   ./scripts/pin_base_digest.sh --update   resolve the current Ubuntu digest with docker,
#                                           rewrite docker/base/pins.env, then write .env
#
# Only --update touches the network for image metadata. Normal runs are reproducible.
# Requires: bash, and for --update: docker.
set -euo pipefail
cd "$(dirname "$0")/.."

PINS=docker/base/pins.env
BASE_TAG="ubuntu:24.04"

if [[ "${1:-}" == "--update" ]]; then
  docker pull "${BASE_TAG}" >/dev/null
  DIGEST="$(docker inspect --format='{{index .RepoDigests 0}}' "${BASE_TAG}")"
  if [[ "${DIGEST}" != *@sha256:* ]]; then
    echo "Could not resolve a digest for ${BASE_TAG}" >&2
    exit 1
  fi
  sed -i "s#^BASE_IMAGE=.*#BASE_IMAGE=${DIGEST}#" "${PINS}"
  echo "Updated ${PINS}: BASE_IMAGE=${DIGEST}. Review the diff and commit it."
fi

# shellcheck disable=SC1090
source "${PINS}"

if [[ "${BASE_IMAGE}" == *PLACEHOLDER* ]]; then
  echo "BASE_IMAGE is not pinned. Run: ./scripts/pin_base_digest.sh --update (needs docker)" >&2
  exit 1
fi
if [[ -z "${ROS_APT_SOURCE_VERSION}" ]]; then
  echo "ROS_APT_SOURCE_VERSION is empty in ${PINS}" >&2
  exit 1
fi

cat > .env <<ENV
# Generated by scripts/pin_base_digest.sh from ${PINS}. Not committed.
BASE_IMAGE=${BASE_IMAGE}
ROS_APT_SOURCE_VERSION=${ROS_APT_SOURCE_VERSION}
ENV
echo "Wrote .env from ${PINS}"
