#!/usr/bin/env bash
# Resolves the base image to a digest and the ROS apt-source version, then writes .env.
# Run once on the development machine, and again only when deliberately upgrading.
# Requires: docker, curl, internet access to Docker Hub and api.github.com.
set -euo pipefail

BASE_TAG="ubuntu:24.04"
ENV_FILE=".env"

docker pull "${BASE_TAG}" >/dev/null
DIGEST="$(docker inspect --format='{{index .RepoDigests 0}}' "${BASE_TAG}")"
if [[ -z "${DIGEST}" || "${DIGEST}" != *@sha256:* ]]; then
  echo "Could not resolve a digest for ${BASE_TAG}" >&2
  exit 1
fi

ROS_APT_SOURCE_VERSION="$(curl -fsSL https://api.github.com/repos/ros-infrastructure/ros-apt-source/releases/latest \
  | grep -F '"tag_name"' | awk -F'"' '{print $4}')"
if [[ -z "${ROS_APT_SOURCE_VERSION}" ]]; then
  echo "Could not resolve ros-apt-source version" >&2
  exit 1
fi

cat > "${ENV_FILE}" <<ENV
# Generated by scripts/pin_base_digest.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Not committed.
BASE_IMAGE=${DIGEST}
ROS_APT_SOURCE_VERSION=${ROS_APT_SOURCE_VERSION}
ENV
echo "Wrote ${ENV_FILE}:"
cat "${ENV_FILE}"
